"""Final numbers for the C1 paper: the single source of every number in the manuscript (writes ../paper_c1/FACTS.md
and CSVs for the figures in ../paper_c1/figdata/). Final model = 3-seed Mammo-CLIP ensemble (640x1024), breast
level, patient-grouped 5-fold cross-validation. CPU only.
"""
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, confusion_matrix, roc_auc_score

from compare_runs import CLASSES, TAB, breast_level, metrics, model_probs

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent / "paper_c1"
FIG = PAPER / "figdata"
RUNS = ["b2_mammoclip_640x1024", "b2_mammoclip_640x1024_s1", "b2_mammoclip_640x1024_s2"]
B = 2000


def main():
    FIG.mkdir(parents=True, exist_ok=True)
    img = pd.read_csv(TAB / "images.csv")
    br = pd.read_csv(TAB / "breasts.csv").merge(pd.read_csv(TAB / "folds.csv"), on="patient").set_index("breast")
    br["y"] = br.label.map({c: i for i, c in enumerate(CLASSES)})
    y, folds, pats = br.y.to_numpy(), br.fold.to_numpy(), br.patient.to_numpy()
    true = pd.read_csv(HERE / "concepts_breast.csv").set_index("breast").loc[br.index]
    mask = pd.read_csv(HERE / "concept_mask_breast.csv").set_index("breast").loc[br.index]
    cols = list(true.columns)
    L = ["# FACTS: every number used in the C1 manuscript (generated by c1_concepts/final_numbers.py)", ""]

    # ---- dataset characteristics
    pat_age = br.groupby("patient").age.first()
    L += ["## Dataset (CDD-CESM)", "",
          f"- patients {br.patient.nunique()}; breasts {len(br)}; images {len(img)} "
          f"(LE {int((img.energy == 'LE').sum())}, DES {int((img.energy == 'DES').sum())}; "
          f"CC {int((img.View == 'CC').sum())}, MLO {int((img.View == 'MLO').sum())})",
          f"- breasts with 4 images {int((br.n_images == 4).sum())}, 2 images {int((br.n_images == 2).sum())}, "
          f"6 images {int((br.n_images == 6).sum())}; patients with both breasts "
          f"{int((br.groupby('patient').size() == 2).sum())}",
          f"- breast labels: " + ", ".join(f"{k} {v}" for k, v in br.label.value_counts().items()),
          f"- age (patients): median {pat_age.median():.0f}, IQR {pat_age.quantile(.25):.0f}-{pat_age.quantile(.75):.0f}, "
          f"range {pat_age.min():.0f}-{pat_age.max():.0f}",
          f"- density (breasts, from LE): " + ", ".join(f"{k} {v}" for k, v in br.density.fillna('missing').value_counts().items()),
          f"- machine (breasts): " + ", ".join(f"{k} {v}" for k, v in br.machine.value_counts().items()),
          f"- post-operative breasts {int(br.postop.sum())}",
          f"- breasts whose image-level labels differ {int((img.groupby('breast').label.nunique() > 1).sum())}",
          "", "Per fold (breasts by label):", "", "| fold | patients | Normal | Benign | Malignant |", "|---|---|---|---|---|"]
    for k in range(5):
        d = br[br.fold == k]
        vc = d.label.value_counts()
        L.append(f"| {k} | {d.patient.nunique()} | {vc.get('Normal', 0)} | {vc.get('Benign', 0)} | {vc.get('Malignant', 0)} |")

    # ---- concept labels
    ex = pd.read_csv(HERE / "excluded_cells.csv")
    L += ["", "## Concept labels", "",
          f"- concepts {len(cols)} (LE {sum(c.startswith('le_') for c in cols)}, DES {sum(c.startswith('des_') for c in cols)})",
          f"- excluded breast cells {int((mask[cols] == 0).sum().sum())} of {len(br) * len(cols)} "
          f"({(mask[cols] == 0).sum().sum() / (len(br) * len(cols)):.2%}); breasts touched {int((mask[cols] == 0).any(axis=1).sum())}; "
          f"excluded image cells {len(ex)}",
          "- extractor validation (from validation/): dev 100 breasts (rules built), held-out test 50 breasts with "
          "frozen extractor v2.0: micro precision 0.995, recall 0.991, F1 0.993 (3 errors in 1,800 cells; 36 concepts at "
          "the time); Findings-column agreement 504/517 = 97.5% (150 breasts) and 1491/1521 = 98.0% (all 566 breasts)",
          f"- breasts with at least one concept among abnormal: "
          f"{(true.loc[br.label != 'Normal', cols].sum(1) > 0).mean():.1%}"]

    # ---- final model predictions
    preds = [breast_level(r)[0].loc[br.index, cols].to_numpy() for r in RUNS]
    Xp = np.mean(preds, axis=0)
    bb = np.mean([model_probs(r, br)[f"{r} / black box"] for r in RUNS], axis=0)
    cbm = np.zeros_like(bb)
    coefs = []
    for k in np.unique(folds):
        tr, te = folds != k, folds == k
        m = LogisticRegression(C=1.0, max_iter=5000).fit(Xp[tr], y[tr])
        cbm[te] = m.predict_proba(Xp[te])
        coefs.append(m.coef_ * Xp[tr].std(0))           # standardised log-odds per SD of concept score
    up = np.unique(pats)
    idx = {p: np.where(pats == p)[0] for p in up}
    rng = np.random.default_rng(0)
    boots = [np.concatenate([idx[p] for p in rng.choice(up, len(up))]) for _ in range(B)]

    def ci(p):
        d = np.array([metrics(p[i], y[i]) for i in boots])
        return metrics(p, y), np.percentile(d, 2.5, axis=0), np.percentile(d, 97.5, axis=0)
    L += ["", "## Main result (3-seed ensemble, 566 breasts; 95% CI by patient bootstrap, 2,000 resamples)", "",
          "| model | accuracy | macro AUC | B-vs-M AUC |", "|---|---|---|---|"]
    for n, p in (("concept bottleneck", cbm), ("black box", bb)):
        pt, lo, hi = ci(p)
        L.append(f"| {n} | " + " | ".join(f"{pt[j]:.3f} ({lo[j]:.3f}-{hi[j]:.3f})" for j in range(3)) + " |")
    d = np.array([metrics(cbm[i], y[i]) - metrics(bb[i], y[i]) for i in boots])
    est = metrics(cbm, y) - metrics(bb, y)
    p2 = np.minimum(1.0, 2 * np.minimum((d <= 0).mean(0), (d >= 0).mean(0)))
    L.append("| difference CBM - black box | " + " | ".join(
        f"{est[j]:+.3f} ({np.percentile(d[:, j], 2.5):+.3f} to {np.percentile(d[:, j], 97.5):+.3f}); two-sided p={p2[j]:.3f}"
        for j in range(3)) + " |")
    L += ["", "Confusion matrix, CBM ensemble (rows true N/B/M, columns predicted N/B/M):", "",
          "```", str(confusion_matrix(y, cbm.argmax(1))), "```", "",
          "Confusion matrix, black-box ensemble:", "", "```", str(confusion_matrix(y, bb.argmax(1))), "```"]
    # per-class recall
    cm = confusion_matrix(y, cbm.argmax(1))
    L.append("- CBM per-class recall: " + ", ".join(f"{c} {cm[i, i] / cm[i].sum():.3f}" for i, c in enumerate(CLASSES)))

    # ---- concept AUCs
    rows = []
    for j, c in enumerate(cols):
        ok = (mask[c] == 1).to_numpy()
        t = true[c].to_numpy()[ok]
        if t.sum() >= 5:
            rows.append({"concept": c, "positives": int(t.sum()), "auc": roc_auc_score(t, Xp[ok, j])})
    ca = pd.DataFrame(rows).sort_values("auc", ascending=False)
    ca.to_csv(FIG / "concept_auc.csv", index=False)
    L += ["", f"## Concept prediction (ensemble, breast level; concepts with >=5 positives: {len(ca)})", "",
          f"- mean concept AUC {ca.auc.mean():.3f}; median {ca.auc.median():.3f}; LE mean "
          f"{ca[ca.concept.str.startswith('le_')].auc.mean():.3f}; DES mean {ca[ca.concept.str.startswith('des_')].auc.mean():.3f}",
          f"- concepts with AUC >= 0.90: {int((ca.auc >= 0.9).sum())}; < 0.70: {int((ca.auc < 0.7).sum())}", "",
          "| concept | positives | AUC |", "|---|---|---|"] + [f"| {r.concept} | {r.positives} | {r.auc:.3f} |" for r in ca.itertuples()]

    # ---- head weights (fold-averaged, standardised), benign-vs-malignant contrast = malignant - benign row
    W = np.mean(coefs, axis=0)                           # 3 x n_concepts
    wd = pd.DataFrame({"concept": cols, "malignant_vs_benign": W[2] - W[1], "abnormal_vs_normal": W[1:].mean(0) - W[0]})
    wd.to_csv(FIG / "head_weights.csv", index=False)
    top = wd.reindex(wd.malignant_vs_benign.abs().sort_values(ascending=False).index).head(12)
    L += ["", "## CBM head weights (fold-averaged; log-odds per SD of the concept score; malignant minus benign)", "",
          "| concept | weight |", "|---|---|"] + [f"| {r.concept} | {r.malignant_vs_benign:+.2f} |" for r in top.itertuples()]
    (PAPER / "FACTS.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L).encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
